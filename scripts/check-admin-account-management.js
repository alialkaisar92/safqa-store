'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const postgres = read('lib/postgres.js');
const admin = read('admin.js');
const auth = read('services/auth-postgres.js');
const html = read('admin.html');

assert(postgres.includes("ALTER TABLE users ADD COLUMN IF NOT EXISTS suspended_until TIMESTAMPTZ"), 'temporary suspension migration is missing');
assert(postgres.includes("ALTER TABLE users ADD COLUMN IF NOT EXISTS ban_reason TEXT"), 'ban reason migration is missing');
assert(postgres.includes('CREATE TABLE IF NOT EXISTS admin_user_actions'), 'admin account audit table is missing');
assert(postgres.includes("const bcrypt = require('bcryptjs')"), 'admin password hashing dependency is missing');
assert(postgres.includes('async function createAdminUser'), 'admin user creation is missing');
assert(postgres.includes('async function updateAdminUser'), 'admin profile update is missing');
assert(postgres.includes('async function resetAdminUserPassword'), 'admin password reset is missing');
assert(postgres.includes('async function setUserAccessState'), 'temporary/permanent access state is missing');
assert(postgres.includes("DELETE FROM auth_sessions WHERE user_id=$1"), 'session revocation on admin password/access action is missing');
assert(postgres.includes('recordAdminUserAction'), 'admin account actions are not audited');
assert(admin.includes("app.post('/api/admin/users'"), 'admin create-user route is missing');
assert(admin.includes("app.patch('/api/admin/users/:id'"), 'admin update-user route is missing');
assert(admin.includes("/reset-password'"), 'admin reset-password route is missing');
assert(admin.includes("/access'"), 'admin access-state route is missing');
assert(admin.includes("app.get('/api/admin/users/:id/actions'"), 'admin account action history route is missing');
assert(admin.includes("if (/^\\/(users|user-)/.test(p)) return 'users';"), 'new user routes are not protected by users permission');
assert(admin.includes('isAccountBlocked(user)'), 'admin access must reject blocked accounts');
assert(!/safeUser\([\s\S]{0,1200}password_hash/.test(admin), 'safe admin user output must not include password_hash');
assert(html.includes('data-action="open-user-create"'), 'admin create-user button is missing');
assert(html.includes('data-edit-user'), 'admin edit-user action is missing');
assert(html.includes('data-reset-user'), 'admin reset-password action is missing');
assert(html.includes('data-access-user'), 'admin access action is missing');
assert(html.includes('data-user-actions'), 'admin account history action is missing');
assert(html.includes('adminUserCreateForm') && html.includes('adminUserResetForm') && html.includes('adminUserAccessForm'), 'admin account forms are missing');
assert(auth.includes('u.banned IS NOT TRUE'), 'existing sessions are not blocked for banned users');
assert(auth.includes('u.suspended_until<=NOW()'), 'existing sessions are not blocked for temporarily suspended users');
assert(auth.includes('ACCOUNT_BANNED') && auth.includes('ACCOUNT_SUSPENDED'), 'login does not distinguish blocked account states safely');
console.log('admin-account-management: PASS');
